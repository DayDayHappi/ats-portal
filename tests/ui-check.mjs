// Optional browser acceptance test. Run against a disposable server seeded by tests/seed_demo.py.
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless: true, executablePath:process.env.CHROMIUM_EXECUTABLE, args: ['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
await page.goto(process.env.PORTAL_TEST_URL || 'http://127.0.0.1:8010');
await page.getByRole('heading',{name:'测试执行',exact:true}).waitFor();
await page.getByLabel('压测模式').selectOption('fixture-custom-mode');
await page.getByRole('link',{name:/自定义扩展场景/}).first().click();
await page.getByRole('tab',{name:/问题/}).click();
await page.getByText('固件错误串',{exact:true}).first().waitFor();
await page.getByRole('button',{name:'在日志中搜索'}).first().click();
await page.getByRole('button',{name:/第 2 行/}).first().waitFor();
await page.getByRole('button',{name:/第 2 行/}).first().click();
await page.locator('.log-line').first().waitFor();
assert.equal(await page.evaluate(()=>window.__xss), undefined);
await page.screenshot({path:process.env.PORTAL_SCREENSHOT_DIR ? `${process.env.PORTAL_SCREENSHOT_DIR}/detail.png` : '/tmp/ats-detail.png',fullPage:true});
await page.getByRole('link',{name:'返回测试记录'}).click();
await page.getByRole('button',{name:'重置筛选'}).click();
await page.getByRole('link',{name:/综合压测/}).first().waitFor();
await page.screenshot({path:process.env.PORTAL_SCREENSHOT_DIR ? `${process.env.PORTAL_SCREENSHOT_DIR}/overview.png` : '/tmp/ats-overview.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:process.env.PORTAL_SCREENSHOT_DIR ? `${process.env.PORTAL_SCREENSHOT_DIR}/mobile.png` : '/tmp/ats-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile page must not overflow');
assert.deepEqual(errors,[]);
await browser.close();
console.log('Browser journey PASS: dynamic mode, problem navigation, original logs, desktop/mobile, no JS errors.');
