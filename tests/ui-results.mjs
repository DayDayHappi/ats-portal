// Run against seed_result_overview.py. Exercises real API data and browser UI.
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
  await page.goto((process.env.PORTAL_TEST_URL||'http://127.0.0.1:8010')+'/#runs/qa-result-overview');
  await page.getByRole('tab',{name:/用例结果/}).waitFor();
  assert.equal(await page.locator('.result-round-row').count(),4,'Attention rounds must replace the flat per-record list');
  assert.equal(await page.getByLabel('仅看有问题的轮次').isChecked(),true);
  const round=page.locator('.result-round-row').filter({has:page.getByText('qa-lap · 第 2 轮',{exact:true})});
  assert.equal(await round.locator('.result-attention-item').count(),2);
  assert.match(await round.textContent(),/第 1 项.*photo/);
  assert.match(await round.textContent(),/第 2 项.*video/);
  assert.ok(!(await round.textContent()).includes('第 3 项'));
  await round.getByRole('button',{name:'查看本轮',exact:true}).click();
  assert.equal(await page.locator('.result-record-row').count(),2);
  const flaggedPass=page.locator('.result-record-row').filter({hasText:'photo'});
  assert.match(await flaggedPass.textContent(),/第 2 次/);
  assert.match(await flaggedPass.textContent(),/PASS/);
  assert.match(await flaggedPass.textContent(),/固件错误串/);
  await page.locator('.result-record-row').filter({hasText:'video'}).locator('summary').click();
  assert.ok((await page.locator('#result-round-detail').textContent()).includes('<img src=x'));
  assert.equal(await page.evaluate(()=>window.__xss),undefined);
  await page.getByLabel('仅看本轮问题记录').uncheck();
  assert.equal(await page.locator('.result-record-row').count(),5,'Same task/repeat retries must not be discarded');
  assert.equal(await page.locator('.result-record-row').filter({hasText:'video'}).count(),2);
  await flaggedPass.getByRole('button',{name:'查看日志',exact:true}).click();
  await page.getByRole('button',{name:'第 2 行：查看上下文',exact:true}).waitFor();
  assert.equal(await page.getByLabel('日志搜索关键词').inputValue(),'TT ERROR');
  await page.getByRole('tab',{name:/用例结果/}).click();
  await page.getByLabel('仅看有问题的轮次').uncheck();
  assert.equal(await page.locator('.result-round-row').count(),5);
  await page.getByRole('button',{name:'收起本轮详情',exact:true}).click();
  assert.ok((await page.locator('#tab-content').textContent()).includes('未标注轮次'));
  assert.ok((await page.locator('#tab-content').textContent()).includes('未关联到具体测试项'));
  await page.locator('.result-round-row').filter({has:page.getByText('other-lap · 第 2 轮',{exact:true})}).getByRole('button',{name:'查看本轮',exact:true}).click();
  assert.equal(await page.locator('.result-record-row').count(),1,'Scenarios with the same cycle number must remain separate');
  assert.match(await page.locator('.result-record-row').textContent(),/第 1 项/);
  await page.getByRole('button',{name:'收起本轮详情',exact:true}).click();
  await page.locator('.result-overview').scrollIntoViewIfNeeded();
  await page.locator('.result-overview').screenshot({path:process.env.PORTAL_RESULTS_SCREENSHOT||'/tmp/ats-results-overview.png'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.setViewportSize({width:1440,height:1100});
  await page.goto((process.env.PORTAL_TEST_URL||'http://127.0.0.1:8010')+'/#runs/qa-many-rounds');
  await page.locator('.result-round-row').getByText('第 27 轮',{exact:true}).waitFor();
  assert.equal(await page.locator('.result-round-row').count(),1,'Failures after many healthy rounds must be surfaced immediately');
  await page.getByRole('button',{name:'查看本轮',exact:true}).click();
  assert.match(await page.locator('.result-record-row').textContent(),/第 30 次/);
  await page.getByLabel('仅看本轮问题记录').uncheck();
  assert.equal(await page.locator('.result-record-row').count(),25);
  await page.locator('#result-round-detail').getByRole('button',{name:'下一页',exact:true}).click();
  assert.equal(await page.locator('.result-record-row').count(),5);
  assert.match(await page.locator('.result-record-row').last().textContent(),/第 30 次/);
  await page.getByRole('button',{name:'收起本轮详情',exact:true}).click();
  await page.getByLabel('仅看有问题的轮次').uncheck();
  assert.equal(await page.locator('.result-round-row').count(),20);
  await page.getByRole('button',{name:'下一页',exact:true}).click();
  assert.equal(await page.locator('.result-round-row').count(),7);
  await page.getByLabel('选择轮次').selectOption({label:'第 1 轮'});
  assert.equal(await page.locator('.result-round-row').count(),1);
  assert.ok((await page.locator('.result-round-row').textContent()).includes('第 1 轮'));
  await page.getByLabel('仅看有问题的轮次').check();
  assert.equal(await page.locator('.result-round-row').count(),0);
  await page.getByText('没有符合条件的轮次',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('Result overview PASS: cycle/task location, repeats, PASS with issues, unknown cycle/status, scenario isolation, retry records, log navigation, safe text, mobile, 810-record filtering and pagination.');
}finally{await browser.close();}
